// State and journal primitives (spec 11.1). state.json is a cache and a log, never an authority:
// gates recompute from sources. The journal is append-only; each entry carries the previous
// entry's hash, and a broken chain is an inconsistency (exit 5). Phase semantics belong to
// lib/run/ (slice A1); this module only guarantees shape, chain and append-only writes.

import { randomBytes } from 'node:crypto';
import { InconsistencyError } from './exit.mjs';
import { canonicalJson, hashJson, sha256 } from './hash.mjs';
import { readJson, withLock, writeJsonAtomic } from './fs.mjs';
import { validateAgainst } from './schema.mjs';

export const GENESIS_PREV = '0'.repeat(64);

/**
 * @typedef {{ seq: number, at: string, event: string, inputs: string, outputs: string, prev: string, hash: string }} JournalEntry
 * @typedef {object} State  see schemas/state.schema.json
 */

/** The hash an entry must carry: sha256 of the canonical JSON of every other field. */
export function entryHash({ seq, at, event, inputs, outputs, prev }) {
  return sha256(canonicalJson({ seq, at, event, inputs, outputs, prev }));
}

/**
 * One-line event text: "<command words> | exit=<n> | key=value ...". The handover's
 * "Verification performed" section is generated by parsing these (parseEvent).
 * @param {{ command: string, exit?: number|null, counts?: Record<string, string|number|boolean> }} e
 */
export function formatEvent({ command, exit = null, counts = {} }) {
  const parts = [String(command).replace(/[|\n]/g, ' ').trim()];
  if (exit !== null && exit !== undefined) parts.push(`exit=${exit}`);
  for (const [k, v] of Object.entries(counts)) parts.push(`${k}=${String(v).replace(/[|\s]+/g, '_')}`);
  return parts.join(' | ');
}

/** @param {string} event @returns {{ command: string, exit: number|null, counts: Record<string, string> }} */
export function parseEvent(event) {
  const [command, ...rest] = String(event).split(' | ');
  const counts = {};
  let exit = null;
  for (const kv of rest) {
    const i = kv.indexOf('=');
    if (i < 0) continue;
    const k = kv.slice(0, i), v = kv.slice(i + 1);
    if (k === 'exit') exit = Number(v); else counts[k] = v;
  }
  return { command, exit, counts };
}

/**
 * Build the next journal entry. inputs and outputs are hashed (canonical JSON) unless already a sha256.
 * @param {JournalEntry|null} prevEntry
 * @param {{ at: string, event: string, inputs?: unknown, outputs?: unknown }} e
 * @returns {JournalEntry}
 */
export function makeEntry(prevEntry, { at, event, inputs = null, outputs = null }) {
  const entry = {
    seq: prevEntry ? prevEntry.seq + 1 : 0,
    at,
    event,
    inputs: asHash(inputs),
    outputs: asHash(outputs),
    prev: prevEntry ? prevEntry.hash : GENESIS_PREV,
  };
  return { ...entry, hash: entryHash(entry) };
}

function asHash(v) {
  return typeof v === 'string' && /^[0-9a-f]{64}$/.test(v) ? v : hashJson(v);
}

/**
 * @param {JournalEntry[]} journal
 * @returns {{ ok: true } | { ok: false, seq: number, reason: string }}
 */
export function verifyJournal(journal) {
  if (!Array.isArray(journal) || journal.length === 0) return { ok: false, seq: 0, reason: 'journal is empty (no genesis entry)' };
  let prev = GENESIS_PREV;
  for (let i = 0; i < journal.length; i++) {
    const e = journal[i];
    if (e.seq !== i) return { ok: false, seq: i, reason: `entry ${i} has seq ${e.seq}` };
    if (e.prev !== prev) return { ok: false, seq: i, reason: `entry ${i} does not carry the previous entry's hash` };
    if (entryHash(e) !== e.hash) return { ok: false, seq: i, reason: `entry ${i} was edited (hash mismatch)` };
    prev = e.hash;
  }
  return { ok: true };
}

/** A run id: r-YYYYMMDD-HHMM-xxxx (UTC). */
export function newRunId(clock, rand = () => randomBytes(2).toString('hex')) {
  const iso = clock.now().toISOString();
  return `r-${iso.slice(0, 10).replace(/-/g, '')}-${iso.slice(11, 16).replace(':', '')}-${rand()}`;
}

/**
 * A fresh state at phase intake with its genesis entry.
 * @param {{ feature: string, runId: string, worktree: string, branch: string, epic?: number|null, at: string }} init
 * @returns {State}
 */
export function initState({ feature, runId, worktree, branch, epic = null, at }) {
  const genesis = makeEntry(null, { at, event: formatEvent({ command: 'genesis', counts: { run: runId } }), inputs: { feature, runId }, outputs: {} });
  return {
    schemaVersion: 1, feature, runId, epic, pr: null, worktree, branch,
    phase: 'intake', wave: 0, inFlight: [], waivers: [], dupeDecisions: [], readyRecords: [], journal: [genesis],
  };
}

/**
 * Append an event to a state (pure; returns a new state).
 * @param {State} state
 * @param {{ at: string, event: string, inputs?: unknown, outputs?: unknown }} e
 */
export function appendJournal(state, e) {
  const last = state.journal[state.journal.length - 1] ?? null;
  return { ...state, journal: [...state.journal, makeEntry(last, e)] };
}

/**
 * Check shape and chain. Anything wrong is exit 5: only the CLI writes this file.
 * @param {unknown} state
 * @param {string} [label]
 */
export function assertStateConsistent(state, label = 'state.json') {
  const { errors } = validateAgainst('state', state);
  if (errors.length) {
    throw new InconsistencyError(`${label} does not match its schema (${errors.length} issue(s))`, {
      failures: errors.map((e) => ({ code: 'state', message: `${label}${e.path === '/' ? '' : e.path}: ${e.message}` })),
    });
  }
  const chain = verifyJournal(state.journal);
  if (!chain.ok) throw new InconsistencyError(`${label}: journal chain broken at entry ${chain.seq}: ${chain.reason}`, { code: 'journal' });
  return state;
}

/**
 * @param {string} statePath
 * @param {{ optional?: boolean }} [opts]
 * @returns {Promise<State|null>}
 */
export async function loadState(statePath, opts = {}) {
  const state = await readJson(statePath, { optional: opts.optional, exit: 5 });
  if (state === null) return null;
  return assertStateConsistent(state, statePath);
}

/**
 * Write a state whose journal extends the one on disk. Refuses (exit 5) a rewrite of history.
 * Call inside withStateLock when a read-modify-write is involved.
 * @param {string} statePath
 * @param {State} next
 */
export async function saveState(statePath, next) {
  assertStateConsistent(next, 'new state');
  const onDisk = await readJson(statePath, { optional: true, exit: 5 });
  if (onDisk) {
    assertStateConsistent(onDisk, statePath);
    const old = onDisk.journal;
    if (next.journal.length < old.length || old.some((e, i) => e.hash !== next.journal[i].hash)) {
      throw new InconsistencyError(`${statePath}: the journal is append-only; the new state rewrites entry history`, { code: 'journal' });
    }
    if (onDisk.runId !== next.runId || onDisk.feature !== next.feature) {
      throw new InconsistencyError(`${statePath}: run id or feature changed`, { code: 'state' });
    }
  }
  await writeJsonAtomic(statePath, next);
  return next;
}

/**
 * Lock, load, apply a pure mutation, append one journal event, save. The unit of every state write.
 * @param {{ state: string, stateLock: string }} paths FeaturePaths (or the two fields)
 * @param {(s: State) => State} mutate may return the state unchanged
 * @param {{ at: string, event: string, inputs?: unknown, outputs?: unknown }} event
 * @returns {Promise<State>}
 */
export async function updateState(paths, mutate, event) {
  return withLock(paths.stateLock, async () => {
    const current = await loadState(paths.state);
    const mutated = mutate(structuredClone(current)) ?? current;
    mutated.journal = current.journal; // mutations never touch the journal directly
    return saveState(paths.state, appendJournal(mutated, event));
  });
}

/**
 * Create state.json for a new run. Refuses when one already exists (intake is idempotent on
 * the archive hash, so it reads first).
 */
export async function createState(paths, init) {
  return withLock(paths.stateLock, async () => {
    const existing = await readJson(paths.state, { optional: true, exit: 5 });
    if (existing) throw new InconsistencyError(`${paths.state} already exists (run ${existing.runId})`, { code: 'state' });
    return saveState(paths.state, initState(init));
  });
}
